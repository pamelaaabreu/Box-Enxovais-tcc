BEGIN;

CREATE TABLE product_variants (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    size VARCHAR(60) NOT NULL CHECK (btrim(size) <> ''),
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    dimensions TEXT,
    included_items JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(included_items) = 'array'),
    simulated BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (product_id, size),
    UNIQUE (product_id, id)
);

ALTER TABLE product_images ADD COLUMN variant_id INTEGER;
ALTER TABLE product_images ADD CONSTRAINT product_images_variant_product_fk
    FOREIGN KEY (product_id, variant_id) REFERENCES product_variants(product_id, id) ON DELETE CASCADE;

ALTER TABLE cart_items ADD COLUMN variant_id INTEGER;
ALTER TABLE cart_items DROP CONSTRAINT cart_items_cart_id_product_id_key;
ALTER TABLE cart_items ADD CONSTRAINT cart_items_variant_product_fk
    FOREIGN KEY (product_id, variant_id) REFERENCES product_variants(product_id, id);
CREATE UNIQUE INDEX cart_items_sellable_key ON cart_items(cart_id, product_id, COALESCE(variant_id, 0));

ALTER TABLE checkout_order_items ADD COLUMN variant_id INTEGER;
ALTER TABLE checkout_order_items ADD CONSTRAINT checkout_order_items_variant_product_fk
    FOREIGN KEY (product_id, variant_id) REFERENCES product_variants(product_id, id);

COMMIT;
