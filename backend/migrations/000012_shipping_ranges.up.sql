CREATE TABLE shipping_ranges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (btrim(name) <> ''),
    start_cep integer NOT NULL CHECK (start_cep BETWEEN 0 AND 99999999),
    end_cep integer NOT NULL CHECK (end_cep BETWEEN start_cep AND 99999999),
    price_cents integer NOT NULL CHECK (price_cents >= 0),
    min_days integer NOT NULL CHECK (min_days >= 0),
    max_days integer NOT NULL CHECK (max_days >= min_days),
    active boolean NOT NULL,
    EXCLUDE USING gist (int4range(start_cep, end_cep, '[]') WITH &&) WHERE (active)
);

