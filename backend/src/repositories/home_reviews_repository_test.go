func newHomeReviewsTestDB(t *testing.T) *sql.DB {
	t.Helper()

	dsn := os.Getenv("REVIEW_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("Defina REVIEW_TEST_DATABASE_URL para executar os testes de integração com PostgreSQL")
	}

	db, err := sql.Open("postgres", dsn)
	if err != nil {
		t.Fatalf("abrir conexão PostgreSQL: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })

	db.SetMaxOpenConns(1)
	db.SetMaxIdleConns(1)

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	if err := db.PingContext(ctx); err != nil {
		t.Fatalf("conectar ao PostgreSQL de teste: %v", err)
	}

	statements := []string{
		`CREATE TEMP TABLE checkout_orders (
			id BIGINT PRIMARY KEY,
			user_id INTEGER NOT NULL,
			status TEXT NOT NULL,
			stock_debited BOOLEAN NOT NULL
		)`,
		`CREATE TEMP TABLE purchase_experience_reviews (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			order_id BIGINT NOT NULL UNIQUE REFERENCES checkout_orders(id),
			user_id INTEGER NOT NULL,
			overall SMALLINT NOT NULL CHECK (overall BETWEEN 1 AND 5),
			navigation SMALLINT CHECK (navigation BETWEEN 1 AND 5),
			service SMALLINT CHECK (service BETWEEN 1 AND 5),
			experience SMALLINT CHECK (experience BETWEEN 1 AND 5),
			comment TEXT NOT NULL DEFAULT '',
			publication_consent BOOLEAN NOT NULL DEFAULT FALSE,
			status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
			created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
			moderated_at TIMESTAMPTZ,
			moderated_by INTEGER
		)`,
	}

	for _, statement := range statements {
		if _, err := db.ExecContext(ctx, statement); err != nil {
			t.Fatalf("criar tabela temporária de teste: %v", err)
		}
	}

	return db
}

func insertHomeReviewsTestOrder(t *testing.T, db *sql.DB, id int64, user int, status string, stockDebited bool) {
	t.Helper()

	_, err := db.Exec(`
		INSERT INTO checkout_orders (id, user_id, status, stock_debited)
		VALUES ($1, $2, $3, $4)
	`, id, user, status, stockDebited)
	if err != nil {
		t.Fatalf("criar pedido %d: %v", id, err)
	}
}

func insertHomeReviewsTestReview(t *testing.T, db *sql.DB, orderID int64, user int, status string, consent bool) int64 {
	t.Helper()

	var id int64
	err := db.QueryRow(`
		INSERT INTO purchase_experience_reviews (
			order_id, user_id, overall, comment, publication_consent, status
		)
		VALUES ($1, $2, 5, 'Avaliação de teste', $3, $4)
		RETURNING id
	`, orderID, user, consent, status).Scan(&id)
	if err != nil {
		t.Fatalf("criar avaliação do pedido %d: %v", orderID, err)
	}
	return id
}

func TestHomeReviewsPublicationRules(t *testing.T) {
	db := newHomeReviewsTestDB(t)
	repo := HomeRepository{DB: db}

	cases := []struct {
		name         string
		status       string
		consent      bool
		orderStatus  string
		stockDebited bool
		public       bool
	}{
		{"aprovada com consentimento", "approved", true, "simulated_approved", true, true},
		{"pendente com consentimento", "pending", true, "simulated_approved", true, false},
		{"rejeitada com consentimento", "rejected", true, "simulated_approved", true, false},
		{"aprovada sem consentimento", "approved", false, "simulated_approved", true, false},
		{"aprovada com pedido cancelado", "approved", true, "cancelled", false, false},
		{"aprovada sem estoque debitado", "approved", true, "simulated_approved", false, false},
		{"aprovada com pedido pendente", "approved", true, "pending", true, false},
	}

	var eligibleID int64
	for i, tc := range cases {
		orderID := int64(i + 1)
		insertHomeReviewsTestOrder(t, db, orderID, 10, tc.orderStatus, tc.stockDebited)
		id := insertHomeReviewsTestReview(t, db, orderID, 10, tc.status, tc.consent)
		if tc.public {
			eligibleID = id
		}
	}

	public, err := repo.Reviews(context.Background(), false)
	if err != nil {
		t.Fatalf("consultar avaliações públicas: %v", err)
	}
	if len(public) != 1 {
		t.Fatalf("avaliações públicas: recebido %d, esperado 1", len(public))
	}
	if public[0].ID != eligibleID {
		t.Fatalf("avaliação pública incorreta: recebido ID %d, esperado %d", public[0].ID, eligibleID)
	}
	if public[0].OrderID != 0 || public[0].Status != "" {
		t.Fatalf("a consulta pública expôs dados administrativos: %+v", public[0])
	}
	if public[0].Navigation != nil || public[0].Service != nil || public[0].Experience != nil {
		t.Fatalf("critérios opcionais nulos não foram preservados: %+v", public[0])
	}

	admin, err := repo.Reviews(context.Background(), true)
	if err != nil {
		t.Fatalf("consultar avaliações administrativas: %v", err)
	}
	if len(admin) != len(cases) {
		t.Fatalf("avaliações administrativas: recebido %d, esperado %d", len(admin), len(cases))
	}
	for _, review := range admin {
		if review.OrderID == 0 || review.Status == "" {
			t.Fatalf("a consulta administrativa perdeu dados de moderação: %+v", review)
		}
	}
}

func TestHomeReviewsModerationAndReopening(t *testing.T) {
	db := newHomeReviewsTestDB(t)
	repo := HomeRepository{DB: db}
	ctx := context.Background()

	insertHomeReviewsTestOrder(t, db, 1, 10, "simulated_approved", true)
	id := insertHomeReviewsTestReview(t, db, 1, 10, "approved", true)

	checks := []struct {
		status     string
		wantPublic int
	}{
		{"pending", 0},
		{"approved", 1},
		{"rejected", 0},
		{"pending", 0},
	}

	for _, tc := range checks {
		t.Run(tc.status, func(t *testing.T) {
			if err := repo.Moderate(ctx, id, 42, tc.status); err != nil {
				t.Fatalf("moderar avaliação para %s: %v", tc.status, err)
			}
			public, err := repo.Reviews(ctx, false)
			if err != nil {
				t.Fatalf("consultar avaliações públicas: %v", err)
			}
			if len(public) != tc.wantPublic {
				t.Fatalf("status %s: %d avaliações públicas, esperado %d", tc.status, len(public), tc.wantPublic)
			}
			var status string
			var moderatedBy int
			var moderatedAt time.Time
			if err := db.QueryRow(`
				SELECT status, moderated_by, moderated_at
				FROM purchase_experience_reviews
				WHERE id = $1
			`, id).Scan(&status, &moderatedBy, &moderatedAt); err != nil {
				t.Fatalf("consultar registro de moderação: %v", err)
			}
			if status != tc.status || moderatedBy != 42 || moderatedAt.IsZero() {
				t.Fatalf("registro de moderação incorreto: status=%s administrador=%d data=%v", status, moderatedBy, moderatedAt)
			}
		})
	}

	if err := repo.Moderate(ctx, 9999, 42, "approved"); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("avaliação inexistente: esperado sql.ErrNoRows, recebido %v", err)
	}
}

func TestHomeReviewsCreationAndDuplicates(t *testing.T) {
	db := newHomeReviewsTestDB(t)
	repo := HomeRepository{DB: db}
	ctx := context.Background()

	insertHomeReviewsTestOrder(t, db, 1, 10, "simulated_approved", true)
	insertHomeReviewsTestOrder(t, db, 2, 10, "simulated_approved", false)
	insertHomeReviewsTestOrder(t, db, 3, 20, "simulated_approved", true)

	review, err := repo.OrderReview(ctx, 10, 1)
	if err != nil || review != nil {
		t.Fatalf("pedido sem avaliação: esperado nil, nil, recebido %+v, %v", review, err)
	}

	input := models.ExperienceReview{
		Overall: 5,
		Comment: "Compra excelente",
		Consent: true,
		Status:  "approved",
	}
	if err := repo.CreateReview(ctx, 10, 1, input); err != nil {
		t.Fatalf("cadastrar avaliação: %v", err)
	}

	review, err = repo.OrderReview(ctx, 10, 1)
	if err != nil || review == nil {
		t.Fatalf("consultar avaliação criada: %+v, %v", review, err)
	}
	if review.Status != "pending" || review.Overall != 5 || !review.Consent || review.Comment != "Compra excelente" {
		t.Fatalf("cadastro não preservou os dados ou aceitou status enviado pelo cliente: %+v", review)
	}

	if err := repo.CreateReview(ctx, 10, 1, input); !errors.Is(err, ErrReviewDuplicate) {
		t.Fatalf("avaliação duplicada: esperado ErrReviewDuplicate, recebido %v", err)
	}
	var count int
	if err := db.QueryRow(`SELECT COUNT(*) FROM purchase_experience_reviews WHERE order_id = 1`).Scan(&count); err != nil || count != 1 {
		t.Fatalf("avaliações duplicadas cadastradas: quantidade=%d erro=%v", count, err)
	}

	if err := repo.CreateReview(ctx, 10, 2, input); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("pedido sem estoque debitado: esperado sql.ErrNoRows, recebido %v", err)
	}
	if err := repo.CreateReview(ctx, 10, 3, input); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("pedido de outro cliente: esperado sql.ErrNoRows, recebido %v", err)
	}
	if err := repo.CreateReview(ctx, 10, 999, input); !errors.Is(err, sql.ErrNoRows) {
		t.Fatalf("pedido inexistente: esperado sql.ErrNoRows, recebido %v", err)
	}

	public, err := repo.Reviews(ctx, false)
	if err != nil || len(public) != 0 {
		t.Fatalf("avaliação recém-criada não deve ser pública: quantidade=%d erro=%v", len(public), err)
	}

	if err := repo.Moderate(ctx, review.ID, 42, "approved"); err != nil {
		t.Fatalf("aprovar avaliação: %v", err)
	}
	public, err = repo.Reviews(ctx, false)
	if err != nil || len(public) != 1 {
		t.Fatalf("avaliação aprovada e autorizada deveria ser pública: quantidade=%d erro=%v", len(public), err)
	}
}
