func TestDashboardSeedPostgres(t *testing.T) {
	database, exec := checkoutTestDB(t)
	exec(`ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100);
 ALTER TABLE users ADD COLUMN password text NOT NULL DEFAULT '!disabled';
 ALTER TABLE users ADD COLUMN IF NOT EXISTS phone varchar(20);
 ALTER TABLE users ADD COLUMN role text NOT NULL DEFAULT 'customer';
 ALTER TABLE users ADD COLUMN created_at timestamptz DEFAULT now();
 UPDATE users SET email='existing-' || id || '@example.invalid',created_at='2020-01-01T00:00:00Z';
 ALTER TABLE users ADD CONSTRAINT seed_email_unique UNIQUE(email);
 CREATE TABLE product_types(id integer PRIMARY KEY,name text);
 INSERT INTO product_types SELECT id,name FROM public.product_types;
 ALTER TABLE products ADD COLUMN product_type_id integer;
 DELETE FROM cart_items;
 DELETE FROM product_variants;
 DELETE FROM products;
 INSERT INTO products(id,name,price,quantity,status,product_type_id)
 SELECT id,name,price,quantity,status,product_type_id FROM public.products;
 INSERT INTO product_variants(id,product_id,size,price,quantity,dimensions)
 SELECT id,product_id,size,price,quantity,dimensions FROM public.product_variants;`)
	sql, err := os.ReadFile("../../cmd/seed-dashboard/seed.sql")
	if err != nil {
		t.Fatal(err)
	}
	stock := func() int64 {
		var v int64
		err := database.QueryRow(`SELECT coalesce(sum(quantity),0) FROM (
 SELECT p.quantity FROM products p WHERE NOT EXISTS(SELECT 1 FROM product_variants v WHERE v.product_id=p.id)
 UNION ALL SELECT quantity FROM product_variants) s`).Scan(&v)
		if err != nil {
			t.Fatal(err)
		}
		return v
	}
	before := stock()
	for range 2 {
		tx, err := database.Begin()
		if err != nil {
			t.Fatal(err)
		}
		if _, err = tx.Exec(string(sql)); err != nil {
			tx.Rollback()
			t.Fatal(err)
		}
		if err = tx.Commit(); err != nil {
			t.Fatal(err)
		}
		var customers, orders, cancelled, inconsistent int
		err = database.QueryRow(`SELECT (SELECT count(*) FROM users WHERE password='!dashboard-demo-login-disabled'),
   (SELECT count(*) FROM checkout_orders),(SELECT count(*) FROM order_cancellations),
   (SELECT count(*) FROM checkout_orders o WHERE products_subtotal_cents-discount_cents+shipping_cents<>total_cents
     OR products_subtotal_cents-discount_cents<>(SELECT sum(quantity*unit_price_cents) FROM checkout_order_items WHERE order_id=o.id))`).Scan(&customers, &orders, &cancelled, &inconsistent)
		if err != nil || customers != 20 || orders != 35 || cancelled != 5 || inconsistent != 0 {
			t.Fatalf("seed counts: %d/%d/%d/%d: %v", customers, orders, cancelled, inconsistent, err)
		}
		if stock() != before-30 {
			t.Fatal("stock debit inconsistent or repeated")
		}
	}
	// The profile-only mode upgrades legacy identifiers without changing ownership,
	// order snapshots or stock. Re-running it is idempotent.
	var originalSnapshot string
	if err := database.QueryRow(`SELECT md5(string_agg(to_jsonb(o)::text, '' ORDER BY id)) FROM checkout_orders o`).Scan(&originalSnapshot); err != nil {
		t.Fatal(err)
	}
	var originalID int
	if err := database.QueryRow(`SELECT id FROM users WHERE email='ana.martins@example.test'`).Scan(&originalID); err != nil {
		t.Fatal(err)
	}
	exec(`UPDATE users SET full_name='Cliente demonstrativo 01',email='dashboard-202611-01@example.invalid',phone=NULL WHERE email='ana.martins@example.test'`)
	for range 2 {
		tx, err := database.Begin()
		if err != nil {
			t.Fatal(err)
		}
		if _, err = tx.Exec(`SET LOCAL box.seed_customers_only='on'`); err != nil {
			tx.Rollback()
			t.Fatal(err)
		}
		if _, err = tx.Exec(string(sql)); err != nil {
			tx.Rollback()
			t.Fatal(err)
		}
		if err = tx.Commit(); err != nil {
			t.Fatal(err)
		}
		var id, complete, totalOrders int
		var snapshot string
		if err := database.QueryRow(`SELECT md5(string_agg(to_jsonb(o)::text, '' ORDER BY id)) FROM checkout_orders o`).Scan(&snapshot); err != nil {
			t.Fatal(err)
		}
		if snapshot != originalSnapshot {
			t.Fatal("profile refresh changed historical order snapshots")
		}
		err = database.QueryRow(`SELECT (SELECT id FROM users WHERE email='ana.martins@example.test'),(SELECT count(*) FROM users WHERE password='!dashboard-demo-login-disabled' AND full_name NOT LIKE 'Cliente demonstrativo%' AND email LIKE '%@example.test' AND phone IS NOT NULL),(SELECT count(*) FROM checkout_orders)`).Scan(&id, &complete, &totalOrders)
		if err != nil || id != originalID || complete != 20 || totalOrders != 35 || stock() != before-30 {
			t.Fatalf("profile refresh changed relationships or stock: %v", err)
		}
	}
	location, _ := time.LoadLocation("America/Sao_Paulo")
	for _, group := range []string{"day", "month"} {
		period := models.DashboardPeriod{From: time.Date(2026, 10, 24, 0, 0, 0, 0, location), Until: time.Date(2026, 11, 23, 0, 0, 0, 0, location), Group: group, Timezone: "America/Sao_Paulo"}
		result, err := (repositories.ProductRepository{DB: database}).Dashboard(context.Background(), period)
		if err != nil {
			t.Fatal(err)
		}
		if result.Orders != 35 || result.NewCustomers != 20 || result.ApprovedOrders != 30 || result.CancelledOrders != 5 {
			t.Fatalf("unexpected dashboard counts: orders=%d customers=%d", result.Orders, result.NewCustomers)
		}
	}
	if os.Getenv("DASHBOARD_SEED_SERVER") != "1" {
		return
	}
	t.Setenv("JWT_SECRET", "dashboard-date-test-only")
	handler := handlers.ProductHandler{Service: services.ProductService{Store: repositories.ProductRepository{DB: database}}}
	mux := http.NewServeMux()
	adminRoute(mux, http.MethodGet, "GET /admin/dashboard", handler.GetDashboard)
	server := http.Server{ReadHeaderTimeout: 5 * time.Second, Handler: http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Access-Control-Allow-Origin", "http://127.0.0.1:4287")
		w.Header().Set("Access-Control-Allow-Headers", "Authorization, Content-Type")
		w.Header().Set("Access-Control-Allow-Methods", "GET, OPTIONS")
		if r.Method == http.MethodOptions {
			w.WriteHeader(http.StatusNoContent)
			return
		}
		mux.ServeHTTP(w, r)
	})}
	listener, err := net.Listen("tcp", "127.0.0.1:8086")
	if err != nil {
		t.Fatal(err)
	}
	defer server.Close()
	go server.Serve(listener)
	t.Log("DASHBOARD_SEED_READY")
	stop := os.Getenv("DASHBOARD_DATES_STOP")
	if stop == "" {
		t.Fatal("stop marker required")
	}
	timer := time.NewTimer(10 * time.Minute)
	defer timer.Stop()
	ticker := time.NewTicker(200 * time.Millisecond)
	defer ticker.Stop()
	for {
		select {
		case <-timer.C:
			t.Fatal("browser timeout")
		case <-ticker.C:
			if _, err := os.Stat(stop); err == nil {
				return
			}
		}
	}
}
