package routes

import (
	"backend/src/handlers"
	"backend/src/models"
	"backend/src/repositories"
	"backend/src/services"
	"encoding/json"
	"fmt"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
	"time"

	"github.com/golang-jwt/jwt/v5"
)

func TestCatalogRegistrationsPostgres(t *testing.T) {
	db, exec := checkoutTestDB(t)
	exec("CREATE TABLE product_types(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(100) UNIQUE NOT NULL); CREATE TABLE brands (LIKE product_types INCLUDING ALL); ALTER TABLE products ADD COLUMN product_type_id INT REFERENCES product_types(id), ADD COLUMN brand_id INT REFERENCES brands(id)")
	mux := http.NewServeMux()
	InitRoutesProducts(mux, handlers.ProductHandler{Service: services.ProductService{Store: repositories.ProductRepository{DB: db}}}, handlers.ProductImageHandler{})
	const secret = "catalog-test-secret"
	t.Setenv("JWT_SECRET", secret)
	request := func(method, path, role, body string, want int) []byte {
		t.Helper()
		r := httptest.NewRequest(method, path, strings.NewReader(body))
		if role != "" {
			token, err := jwt.NewWithClaims(jwt.SigningMethodHS256, models.Claims{UserID: 1, Role: role, RegisteredClaims: jwt.RegisteredClaims{Issuer: "box-enxovais-api", ExpiresAt: jwt.NewNumericDate(time.Now().Add(time.Minute))}}).SignedString([]byte(secret))
			if err != nil {
				t.Fatal(err)
			}
			r.Header.Set("Authorization", "Bearer "+token)
		}
		w := httptest.NewRecorder()
		mux.ServeHTTP(w, r)
		if w.Code != want {
			t.Fatalf("%s %s: status %d, expected %d: %s", method, path, w.Code, want, w.Body.String())
		}
		return w.Body.Bytes()
	}
	for _, spec := range []struct{ resource, column string }{{"categories", "product_type_id"}, {"brands", "brand_id"}} {
		t.Run(spec.resource, func(t *testing.T) {
			path := "/admin/catalog/" + spec.resource
			request("GET", path, "", "", 401)
			request("POST", path, "customer", `{"name":"Teste"}`, 403)
			if got := string(request("GET", path, "admin", "", 200)); strings.TrimSpace(got) != "[]" {
				t.Fatalf("expected empty list: %s", got)
			}
			request("POST", path, "admin", `{"name":"  "}`, 400)
			request("POST", path, "admin", `{"name":"`+strings.Repeat("x", 101)+`"}`, 400)
			var item models.ProductType
			if err := json.Unmarshal(request("POST", path, "admin", `{"name":"  Casa   Bela  "}`, 201), &item); err != nil || item.Name != "Casa Bela" {
				t.Fatalf("unexpected created item: %+v %v", item, err)
			}
			request("POST", path, "admin", `{"name":"casa bela"}`, 409)
			target := fmt.Sprintf("%s/%d", path, item.ID)
			request("PATCH", target, "admin", `{"name":"Renomeado"}`, 200)
			exec(fmt.Sprintf("UPDATE products SET %s=%d WHERE id=1", spec.column, item.ID))
			var rows []repositories.CatalogRegistration
			if err := json.Unmarshal(request("GET", path, "admin", "", 200), &rows); err != nil || len(rows) != 1 || rows[0].ProductCount != 1 || rows[0].Name != "Renomeado" {
				t.Fatalf("unexpected list: %+v %v", rows, err)
			}
			request("DELETE", target, "admin", "", 409)
			exec("UPDATE products SET " + spec.column + "=NULL WHERE id=1")
			request("DELETE", target, "admin", "", 204)
			request("PATCH", target, "admin", `{"name":"Ausente"}`, 404)
			request("DELETE", target, "admin", "", 404)
		})
	}
}
